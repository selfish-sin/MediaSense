def build_prompt_vars(options: Dict[str, Any]) -> Dict[str, str]:
    """将用户选项映射为 prompt 模板变量"""
    tone = options.get("tone", "学术严谨")
    wc = options.get("word_count", "3000")
    fmt = options.get("format", "Markdown")
    purpose = options.get("purpose", "学习笔记")

    # 支持自定义值：当选项值为 "自定义" 时读取 _custom 字段
    td = TONE_DESCS.get(tone, f"使用{tone}语气")
    if tone == "自定义":
        td = options.get("tone_custom", "")

    wcd = WORD_COUNT_DESCS.get(wc, "")
    if wc == "自定义":
        wcd = options.get("word_count_custom", "")

    fd = FORMAT_DESCS.get(fmt, f"使用{fmt}格式输出")
    if fmt == "自定义":
        fd = options.get("format_custom", "")

    pd = PURPOSE_DESCS.get(purpose, f"面向{purpose}场景")
    if purpose == "自定义":
        pd = options.get("purpose_custom", "")

    # 构建默认占位变量（不再需要 OCR 说明）
    ocr_note = ""

    return {
        "{{TONE_DESC}}": td,
        "{{WORD_COUNT_DESC}}": wcd,
        "{{FORMAT_DESC}}": fd,
        "{{PURPOSE_DESC}}": pd,
        "{{OCR_NOTE}}": ocr_note,
        "{{TITLE_RULE}}": "\n\n# 标题生成规则（所有章节/论点/事件的标题必须遵守）\n标题必须从原文中提取关键原话或关键词组，严格禁止自行编造标题。若原文中找不到合适的原话，请标注【标题待确认】，不得用你自己的话概括一个标题。",
    }


